#!/usr/bin/env python3
"""
Setup script for Feast benchmark using NYC Taxi dataset.

This script:
1. Downloads NYC Taxi data (same as other featurestore-benchmarks)
2. Creates Feast feature definitions
3. Materializes features to the online store

Usage:
    python setup_feast_benchmark.py --store redis --features 50
    python setup_feast_benchmark.py --store dynamodb --features 200
"""
import argparse
import os
import shutil
from datetime import datetime, timedelta
from pathlib import Path

import pandas as pd
import requests
from feast import Entity, FeatureStore, FeatureView, Field, FileSource
from feast.types import Float64, Int64, String
from feast.value_type import ValueType


NYC_TAXI_URL = "https://repo.hops.works/dev/davit/nyc_taxi/rides500.csv"


def download_nyc_taxi_data(output_path: str) -> pd.DataFrame:
    """Download NYC Taxi dataset used by featurestore-benchmarks."""
    print(f"Downloading NYC Taxi data from {NYC_TAXI_URL}...")
    
    response = requests.get(NYC_TAXI_URL)
    response.raise_for_status()
    
    # Save CSV
    csv_path = os.path.join(output_path, "nyc_taxi.csv")
    with open(csv_path, "wb") as f:
        f.write(response.content)
    
    # Load and process
    df = pd.read_csv(csv_path)
    print(f"Downloaded {len(df)} rows with columns: {list(df.columns)}")
    
    return df


def prepare_feature_data(df: pd.DataFrame, output_path: str, num_features: int) -> str:
    """Prepare feature data in Feast-compatible format."""
    print(f"Preparing feature data with {num_features} features...")
    
    # Create entity column
    df["user_id"] = [f"user_{i}" for i in range(len(df))]
    df["event_timestamp"] = datetime.now()
    
    # Select/generate features
    numeric_cols = df.select_dtypes(include=["float64", "int64"]).columns.tolist()
    
    feature_data = {
        "user_id": df["user_id"],
        "event_timestamp": df["event_timestamp"],
    }
    
    # Use existing numeric columns first
    for i, col in enumerate(numeric_cols[:num_features]):
        feature_data[f"feature_{i}"] = df[col].astype(float)
    
    # Generate additional features if needed
    existing = len(numeric_cols)
    for i in range(existing, num_features):
        feature_data[f"feature_{i}"] = [float(i + j * 0.1) for j in range(len(df))]
    
    feature_df = pd.DataFrame(feature_data)
    
    parquet_path = os.path.join(output_path, "features.parquet")
    feature_df.to_parquet(parquet_path)
    print(f"Saved {len(feature_df)} rows with {num_features} features to {parquet_path}")
    
    return parquet_path


def create_feature_store_config(
    repo_path: str,
    store_type: str,
    store_config: dict
) -> None:
    """Create feature_store.yaml configuration."""
    
    config_templates = {
        "sqlite": f"""
project: feast_benchmark
provider: local
registry: {repo_path}/registry.db
online_store:
  type: sqlite
  path: {repo_path}/online_store.db
entity_key_serialization_version: 3
""",
        "redis": f"""
project: feast_benchmark
provider: local
registry: {repo_path}/registry.db
online_store:
  type: redis
  connection_string: {store_config.get('connection_string', 'localhost:6379')}
entity_key_serialization_version: 3
""",
        "dynamodb": f"""
project: feast_benchmark
provider: aws
registry: {repo_path}/registry.db
online_store:
  type: dynamodb
  region: {store_config.get('region', 'us-east-1')}
entity_key_serialization_version: 3
""",
        "postgres": f"""
project: feast_benchmark
provider: local
registry: {repo_path}/registry.db
online_store:
  type: postgres
  host: {store_config.get('host', 'localhost')}
  port: {store_config.get('port', 5432)}
  database: {store_config.get('database', 'feast')}
  user: {store_config.get('user', 'feast')}
  password: {store_config.get('password', 'feast')}
entity_key_serialization_version: 3
""",
    }
    
    config = config_templates.get(store_type, config_templates["sqlite"])
    
    config_path = os.path.join(repo_path, "feature_store.yaml")
    with open(config_path, "w") as f:
        f.write(config.strip())
    
    print(f"Created feature_store.yaml for {store_type}")


def create_feature_definitions(repo_path: str, num_features: int) -> None:
    """Create Feast feature definitions."""
    
    features_py = f'''"""
NYC Taxi feature definitions for benchmark.
Auto-generated by setup_feast_benchmark.py
"""
from datetime import timedelta
from feast import Entity, FeatureView, Field, FileSource, FeatureService
from feast.types import Float64
from feast.value_type import ValueType

# Entity
user = Entity(
    name="user_id",
    join_keys=["user_id"],
    value_type=ValueType.STRING,
    description="Benchmark entity (maps to taxi ride)"
)

# Data source
source = FileSource(
    path="{repo_path}/features.parquet",
    timestamp_field="event_timestamp"
)

# Feature schema
schema = [
    Field(name=f"feature_{{i}}", dtype=Float64)
    for i in range({num_features})
]

# Feature view
bench_fv = FeatureView(
    name="bench_fv",
    entities=[user],
    schema=schema,
    source=source,
    ttl=timedelta(days=1)
)

# Feature service for HTTP API
bench_service = FeatureService(
    name="bench_service",
    features=[bench_fv]
)
'''
    
    features_path = os.path.join(repo_path, "features.py")
    with open(features_path, "w") as f:
        f.write(features_py)
    
    print(f"Created feature definitions with {num_features} features")


def setup_and_materialize(repo_path: str, num_features: int) -> None:
    """Apply feature definitions and materialize to online store."""
    print("Setting up FeatureStore...")
    
    fs = FeatureStore(repo_path=repo_path)
    
    # Create feature definitions directly
    print("Creating feature definitions...")
    
    user = Entity(
        name="user_id",
        join_keys=["user_id"],
        value_type=ValueType.STRING,
        description="Benchmark entity"
    )
    
    source = FileSource(
        path=os.path.join(repo_path, "features.parquet"),
        timestamp_field="event_timestamp"
    )
    
    schema = [Field(name=f"feature_{i}", dtype=Float64) for i in range(num_features)]
    
    fv = FeatureView(
        name="bench_fv",
        entities=[user],
        schema=schema,
        source=source,
        ttl=timedelta(days=1)
    )
    
    # Apply definitions
    print("Applying feature definitions...")
    fs.apply([user, fv])
    
    # Materialize
    print("Materializing features to online store...")
    fs.materialize(
        start_date=datetime.now() - timedelta(days=1),
        end_date=datetime.now()
    )
    
    print("Materialization complete!")
    
    # Verify
    print("\nVerifying setup...")
    entities = [{"user_id": "user_0"}]
    features = ["bench_fv:feature_0", "bench_fv:feature_1"]
    result = fs.get_online_features(features=features, entity_rows=entities)
    print(f"Sample result: {result.to_dict()}")


def main():
    parser = argparse.ArgumentParser(
        description="Setup Feast benchmark with NYC Taxi data"
    )
    parser.add_argument(
        "--store",
        choices=["sqlite", "redis", "dynamodb", "postgres"],
        default="sqlite",
        help="Online store type"
    )
    parser.add_argument(
        "--features",
        type=int,
        default=50,
        help="Number of features (50 or 200)"
    )
    parser.add_argument(
        "--repo-path",
        default="/tmp/feast_benchmark",
        help="Path for Feast repository"
    )
    parser.add_argument(
        "--redis-host",
        default="localhost:6379",
        help="Redis connection string"
    )
    parser.add_argument(
        "--dynamodb-region",
        default="us-east-1",
        help="AWS region for DynamoDB"
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Clean existing repo before setup"
    )
    
    args = parser.parse_args()
    
    repo_path = args.repo_path
    
    # Clean if requested
    if args.clean and os.path.exists(repo_path):
        print(f"Cleaning existing repo at {repo_path}...")
        shutil.rmtree(repo_path)
    
    # Create repo directory
    os.makedirs(repo_path, exist_ok=True)
    
    # Store config
    store_config = {
        "connection_string": args.redis_host,
        "region": args.dynamodb_region,
    }
    
    # Setup steps
    print(f"\n{'='*60}")
    print(f"Setting up Feast Benchmark")
    print(f"Store: {args.store}")
    print(f"Features: {args.features}")
    print(f"Repo: {repo_path}")
    print(f"{'='*60}\n")
    
    # 1. Download data
    df = download_nyc_taxi_data(repo_path)
    
    # 2. Prepare features
    prepare_feature_data(df, repo_path, args.features)
    
    # 3. Create config
    create_feature_store_config(repo_path, args.store, store_config)
    
    # 4. Create feature definitions
    create_feature_definitions(repo_path, args.features)
    
    # 5. Setup and materialize
    setup_and_materialize(repo_path, args.features)
    
    print(f"\n{'='*60}")
    print("Setup complete! Run benchmark with:")
    print(f"  export FEAST_REPO_PATH={repo_path}")
    print(f"  locust -f locustfile_feast.py")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()
